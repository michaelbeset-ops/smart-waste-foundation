    wp_enqueue_style( 'b-advice-style', get_stylesheet_uri(), [], '1.0.0' );
}
add_action( 'wp_enqueue_scripts', 'b_advice_scripts' );

/* ==============================
   CONTACT FORM HANDLER
   ============================== */
function b_advice_handle_contact_form() {
    if ( ! isset( $_POST['ba_contact_nonce'] ) ) return null;
    if ( ! wp_verify_nonce( sanitize_text_field( wp_unslash( $_POST['ba_contact_nonce'] ) ), 'ba_contact_form' ) ) {
        return 'error';
    }

    $naam     = sanitize_text_field( wp_unslash( $_POST['naam']     ?? '' ) );
    $email    = sanitize_email(      wp_unslash( $_POST['email']    ?? '' ) );
    $telefoon = sanitize_text_field( wp_unslash( $_POST['telefoon'] ?? '' ) );
    $bericht  = sanitize_textarea_field( wp_unslash( $_POST['bericht'] ?? '' ) );

    if ( ! $naam || ! $email || ! $bericht || ! is_email( $email ) ) {
        return 'error';
    }

    $to      = get_option( 'admin_email' );
    $subject = 'Contactformulier B-Advice van ' . $naam;
    $body    = "Naam: {$naam}\nE-mail: {$email}\nTelefoon: {$telefoon}\n\nBericht:\n{$bericht}";
    $headers = [
        'Content-Type: text/plain; charset=UTF-8',
        'Reply-To: ' . $email,
    ];

    return wp_mail( $to, $subject, $body, $headers ) ? 'success' : 'error';
}

